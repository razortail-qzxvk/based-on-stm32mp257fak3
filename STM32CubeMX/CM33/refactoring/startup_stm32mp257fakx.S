.section .text.Reset_Handler
.weak Reset_Handler
.type Reset_Handler, %function
  Reset_Handler:
    ldr  sp, =_estack
    bl   SystemInit

    ldr  r0, =_sdata
    ldr  r1, =_edata
    ldr  r2, =_sidata
    movs r3, #0
    b    LoopCopyDataInit

CopyDataInit:
    ldr  r4, [r2, r3]
    str  r4, [r0, r3]
    adds r3, r3, #4

LoopCopyDataInit:
    adds r4, r0, r3
    cmp  r4, r1
    bcc  CopyDataInit

    ldr  r2, =_sbss
    b    LoopFillZerobss

FillZerobss:
    movs r3, #0
    str  r3, [r2], #4

LoopFillZerobss:
    ldr  r3, = _ebss
    cmp  r2, r3
    bcc  FillZerobss

    bl   __libc_init_array

    bl   main

LoopForever:
    b LoopForever

.size Reset_Handler, .-Reset_Handler

.section .text.Default_Handler, "ax", %progbits
Default_Handler:
Infinite_Loop:
    b    Infinite_Loop
.size Default_Handler, .-Default_Handler


